await ev('__world.P.pos.set(2.6,0,-2.7);__world.setIso(3);__world.setYaw(Math.PI/2)');
await send('Input.dispatchKeyEvent',{type:'keyDown',key:'w',code:'KeyW',windowsVirtualKeyCode:87});
